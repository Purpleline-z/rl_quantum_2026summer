"""Builds RESULTS_transductive.md: the hand-written narrative (results_narrative_transductive.md) with every {{TABLE:name}} replaced by a table generated from the result JSONs.
  python3 td_report.py      (run from this directory; tables whose result directories do not exist yet are marked 'not run')
Tables: data_facts, dev_forward, dev_standard, mechanism, confirm1, confirm2 (td_confirm.py with TD1_spec.json)."""
import json
import re
from pathlib import Path

import pandas as pd

import td_confirm as C
import td_tables as T

HERE = Path(__file__).resolve().parent; RES = T.RESULTS


def have(name): return (RES / name).is_dir() and any((RES / name).glob("seed*.json"))


def dev_forward() -> str:
    dirs = [d for d in ("dev1", "dev2", "dev3", "dev5") if have(d)]
    if not dirs: return "*not run*"
    df = T.load(dirs).drop_duplicates(subset=["seed", "cut", "window", "learner"]); t = T.dev_table(df, "BASE", None, ["FA", "FB"], ("auc", "acc", "ll", "far_auc"))
    t = t[["window", "learner", "n_seeds", "auc", "auc_ci", "auc_p", "acc", "acc_ci", "acc_p", "ll", "far_auc"]]
    return T.fmt(t) + "\n\n(`BASE` pooled over the development directories; TW rows of dev1 were invalid (cache-key collision) and are excluded; `dev4` was stopped after 24 of 120 units and is not used.)"


def dev_standard() -> str:
    if not have("devs1"): return "*not run*"
    df = T.load(["devs1"]); df["window"] = "T"; out = []
    for sp in ("A", "B"):
        d = df[df.split == sp]; t = T.dev_table(d, "BASE", None, ["T"], ("auc", "acc", "ll", "far_auc")); t.insert(0, "split", sp); out.append(t.drop(columns=["window"]))
    t = pd.concat(out); return T.fmt(t[["split", "learner", "n_seeds", "auc", "auc_ci", "auc_p", "acc", "acc_ci", "acc_p", "ll", "far_auc"]])


def mechanism() -> str:
    f = RES / "mechanism_dev_L_trans_win.csv"
    if not f.exists(): return "*not run*"
    df = pd.read_csv(f); out = []
    for w in ("FA", "FB"):
        d = df[df.window == w].copy(); d["distance to nearest past node"] = pd.qcut(d.nov_past, 4, labels=["Q1 (nearest)", "Q2", "Q3", "Q4 (farthest)"])
        g = d.groupby("distance to nearest past node", observed=True).agg(n=("dacc", "size"), mean_distance=("nov_past", "mean"), d_acc=("dacc", "mean"), d_logloss=("dll", "mean")).reset_index(); g.insert(0, "window", w); out.append(g)
    return T.md(pd.concat(out), 4)


def table(name: str) -> str:
    if name == "data_facts": f = RES / "data_facts.md"; return f.read_text() if f.exists() else "*not generated*"
    if name == "dev_forward": return dev_forward()
    if name == "dev_standard": return dev_standard()
    if name == "mechanism": return mechanism()
    m = re.match(r"confirm([12])$", name)
    if m:
        spec = json.loads((HERE / "TD1_spec.json").read_text()); b = spec["blocks"][int(m.group(1)) - 1]
        if not have(b["forward"][0]): return "*not run*"
        import io, contextlib
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            print(f"## Block {b['name']} (seeds {b['seeds']})\n"); print(C.forward_tables(spec, b["forward"], 1000))
            if b.get("standard") and have(b["standard"][0]): print(f"\n### {b['name']}: standard random splits (secondary)\n"); print(C.standard_tables(spec, b["standard"], "standard", 1000))
            else: print("\n*standard splits: not run*")
            if b.get("blocked") and have(b["blocked"][0]): print(f"\n### {b['name']}: time-blocked split (secondary)\n"); print(C.standard_tables(spec, b["blocked"], "blocked", 1000))
            else: print("\n*time-blocked split: not run*")
        return buf.getvalue()
    raise KeyError(name)


if __name__ == "__main__":
    text = (HERE / "results_narrative_transductive.md").read_text()
    text = re.sub(r"\{\{TABLE:([A-Za-z0-9_]+)\}\}", lambda mo: table(mo.group(1)), text)
    (HERE / "RESULTS_transductive.md").write_text("<!-- generated by td_report.py from results_narrative_transductive.md and the result JSONs; do not edit by hand -->\n" + text); print("written")
