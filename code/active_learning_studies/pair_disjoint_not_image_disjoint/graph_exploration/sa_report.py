"""Builds RESULTS_synthetic_anchors.md: hand-written narrative (results_narrative_synthetic_anchors.md) with every {{TABLE:name}} replaced by a table generated from the result files.
  python3 sa_report.py      (run from this directory)
Names: dev1..dev5 (development screens, gains over lap3_k10_st4), gap_<bank>, anchor_only{,2,3}, ideal_graph, confirm1 / confirm2 (frozen SA1_spec.json; blocked dirs confirm1_blocked / confirm2_blocked), confirm1_budget."""
import glob, json, re
from pathlib import Path
import pandas as pd
import sa_tables as T

HERE = Path(__file__).resolve().parent; RES = HERE.parents[1] / "new_directions" / "results" / "syn"; BASE = "lap3_k10_st4"
METRICS = "auc,acc,far_auc,far_acc,near_auc,near_acc,ll"


def have(name): return (RES / name).is_dir() and any((RES / name).glob("seed*.json"))


def dev(name, metrics=METRICS, splits="A,B", only=None):
    if not have(name): return f"*{name}: not run*"
    t = T.dev_table(T.load(RES / name), BASE, metrics.split(","), splits.split(","), only); return T.md(t[[c for c in t.columns if not (c.endswith("_p") and c not in ("auc_p", "acc_p", "far_auc_p", "far_acc_p"))]])


def anchor_only(d):
    rows = [r for f in glob.glob(str(RES / d / "*.json")) for r in json.load(open(f))]
    if not rows: return "*not run*"
    df = pd.DataFrame(rows); g = df.groupby(["split", "learner"])[["auc", "acc", "far_auc", "far_acc", "near_auc", "near_acc"]].mean().reset_index(); g["n_seeds"] = df.groupby(["split", "learner"]).seed.nunique().to_numpy(); return T.md(g, "{:.3f}")


def table(name: str) -> str:
    if re.match(r"dev[1-5]$", name): return dev(name)
    if name.startswith("gap_"): f = RES / f"{name}.md"; return f.read_text() if f.exists() else "*not generated*"
    if name.startswith("anchor_only"): return anchor_only(name)
    if name == "ideal_graph": f = RES / "graph_stats_ideal.md"; return f.read_text() if f.exists() else "*not generated*"
    m = re.match(r"confirm([12])$", name)
    if m:
        d = f"confirm{m.group(1)}"
        if not have(d): return f"*{d}: not run*"
        spec = json.loads((HERE / "SA1_spec.json").read_text()); return T.confirm(spec, T.load(RES / d), T.load(RES / f"{d}_blocked") if have(f"{d}_blocked") else None)
    m = re.match(r"confirm([12])_budget$", name)
    if m:
        d = f"confirm{m.group(1)}"
        if not have(d): return f"*{d}: not run*"
        spec = json.loads((HERE / "SA1_spec.json").read_text()); df = T.load(RES / d); return "\n\n".join(f"`{c['name']}`\n\n" + T.md(T.budget_table(df, c["name"], spec["baseline"])) for c in spec["candidates"])
    raise KeyError(name)


if __name__ == "__main__":
    text = (HERE / "results_narrative_synthetic_anchors.md").read_text(); text = re.sub(r"\{\{TABLE:([A-Za-z0-9_]+)\}\}", lambda mo: table(mo.group(1)), text)
    (HERE / "RESULTS_synthetic_anchors.md").write_text("<!-- generated by sa_report.py from results_narrative_synthetic_anchors.md and the result files; do not edit by hand -->\n" + text); print("written")
