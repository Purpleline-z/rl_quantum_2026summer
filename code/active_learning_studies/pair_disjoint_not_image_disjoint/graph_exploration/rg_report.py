"""Builds RESULTS_regularisers.md: the hand-written narrative (results_narrative_regularisers.md) with every {{TABLE:name}} replaced by a table generated from the result JSONs.
  python3 rg_report.py      (run from this directory)"""
import json, re
from pathlib import Path
import numpy as np, pandas as pd
import rg_tables as T

HERE = Path(__file__).resolve().parent; RES = HERE.parents[1] / "new_directions" / "results" / "rg"


def dirs(*names): return [RES / n for n in names if (RES / n).is_dir() and any((RES / n).glob("seed*.json"))]


def dev(names, ref):
    f = T.load(dirs(*names)); return T.fmt_md(T.short(T.dev_table(f, ref))) if len(f) else "*not run*"


def strata_table(names, cand, ref):
    """Gain of cand over ref by anchor stratum (standard / anchor-far / anchor-near), per split (mean over seeds of per-seed paired gains, uncorrected Wilcoxon p)."""
    f = T.load(dirs(*names)); rows = []
    for split in sorted(f.split.unique()):
        for m in ("auc", "acc", "ll", "auc_far", "acc_far", "ll_far", "auc_near", "acc_near", "ll_near"):
            p = T.per_seed(f, split, m, cand, ref); s = T.summarize(p); rows.append({"split": split, "metric": m, "n_seeds": s["n_seeds"], "gain": s["gain"], "lo": s["lo"], "hi": s["hi"], "share_better": s["share_better"], "p_uncorrected": T.wil(p)})
    return T.fmt_md(pd.DataFrame(rows))


def n_far(names):
    f = T.load(dirs(*names)); g = f[f.learner == f.learner.iloc[0]]
    return T.fmt_md(g.groupby("split")[["n_test", "n_far", "n_near"]].mean().reset_index(), "{:.1f}")


def confirm(spec_name, dir_names):
    spec = json.loads((HERE / spec_name).read_text()); f = T.load(dirs(*dir_names)); out = T.run_tests(f, spec); v, label = T.verdict(out, spec)
    cols = ["family", "split", "metric", "a", "b", "n_seeds", "gain", "lo", "hi", "share_better", "p", "holm"]
    return T.fmt_md(out[cols]) + "\n\n**Verdicts by the pre-registered rule**\n\n" + T.fmt_md(v) + f"\n\n**Overall (pre-registered rule): {label}**"


def table(name: str) -> str:
    if name == "dev1_ref": return dev(["dev1"], "lap3_k10_st4")
    if name == "dev1_tuned": return dev(["dev1"], "aw8_all_st2lr0.5")
    if name == "dev2_ref": return dev(["dev2"], "lap3_k10_st4")
    if name == "dev3_ref": return dev(["dev3"], "lap3_k10_st4")
    if name == "far_counts": return n_far(["dev1"])
    if name == "far_conf": return n_far(["conf"])
    m = re.match(r"strata:(.+?):(.+?):(.+?)$", name)   # strata:<dirs comma>:<cand>:<ref>
    if m: return strata_table(m.group(1).split(","), m.group(2), m.group(3))
    m = re.match(r"confirm:(.+?):(.+)$", name)         # confirm:<spec>:<dirs comma>
    if m: return confirm(m.group(1), m.group(2).split(","))
    return f"*unknown table {name}*"


if __name__ == "__main__":
    narrative = (HERE / "results_narrative_regularisers.md").read_text()
    out = "<!-- generated by rg_report.py from results_narrative_regularisers.md and the result JSONs; do not edit by hand -->\n" + re.sub(r"\{\{TABLE:(.+?)\}\}", lambda m: table(m.group(1)), narrative)
    (HERE / "RESULTS_regularisers.md").write_text(out); print("wrote RESULTS_regularisers.md", len(out))
