"""Builds RESULTS_temporal_graph.md: the hand-written narrative (results_narrative_temporal_graph.md) with every {{TABLE:name}} replaced by a table generated from the result JSONs.
  python3 tg_report.py      (run from this directory; tables whose result directory does not exist yet are marked 'not run')
Table names: dev1 / dev2 / devb (development screens), dev1_xr, graph_stats (file written by tg_graph_stats.py), budget_<dir>_<cand>, confirm (frozen spec TG1_spec.json: A/B directory `confirm`, blocked directory `confirm_blocked`), confirm_extra."""
import json
import re
from pathlib import Path

import pandas as pd

import tg_tables as T

HERE = Path(__file__).resolve().parent; RES = HERE.parents[1] / "new_directions" / "results" / "tg"
BASE = "lap3_k10_st4"


def have(name): return (RES / name).is_dir() and any((RES / name).glob("seed*.json"))


def dev(name, metrics="auc,acc,far_auc,far_acc,near_auc,near_acc,ll", splits="A,B", only=None, base=BASE):
    if not have(name): return f"*{name}: not run*"
    df = T.load(RES / name); t = T.dev_table(df, base, metrics.split(","), splits.split(","), only)
    return T.md(t[[c for c in t.columns if not (c.endswith("_p") and c not in ("auc_p", "acc_p", "far_auc_p", "far_acc_p"))]])


def table(name: str) -> str:
    if name == "dev1": return dev("dev1", only=[n for n in sorted(set(T.load(RES / "dev1").learner)) if n.startswith("tg_") and "xr" not in n]) if have("dev1") else "*dev1: not run*"
    if name == "dev1_xr": return dev("dev1", only=[n for n in sorted(set(T.load(RES / "dev1").learner)) if "xr" in n], metrics="auc,acc,far_auc,far_acc,near_auc,near_acc,ll") if have("dev1") else "*not run*"
    if name == "dev2": return dev("dev2")
    if name == "devb": return dev("devb", metrics="auc,acc,far_auc,far_acc,inb_auc,inb_acc,ll", splits="blocked")
    if name == "dev_pool": return dev("dev_pool") if have("dev_pool") else "*not run*"
    if name == "graph_stats":
        f = RES / "graph_stats.md"; return f.read_text() if f.exists() else "*not generated*"
    if name == "confirm":
        if not have("confirm"): return "*confirmation: not run*"
        spec = json.loads((HERE / "TG1_spec.json").read_text()); return T.confirm(spec, T.load(RES / "confirm"), T.load(RES / "confirm_blocked") if have("confirm_blocked") else None)
    if name == "confirm_budget":
        if not have("confirm"): return "*confirmation: not run*"
        spec = json.loads((HERE / "TG1_spec.json").read_text()); df = T.load(RES / "confirm"); return "\n\n".join(f"`{c['name']}`\n\n" + T.md(T.budget_table(df, c["name"], spec["baseline"])) for c in spec["candidates"])
    m = re.match(r"extra_([a-z0-9_]+)$", name)
    if m:   # extra post-freeze runs on the spare seeds (descriptive), directory results/tg/<m>
        return dev(m.group(1))
    raise KeyError(name)


if __name__ == "__main__":
    text = (HERE / "results_narrative_temporal_graph.md").read_text()
    text = re.sub(r"\{\{TABLE:([A-Za-z0-9_]+)\}\}", lambda mo: table(mo.group(1)), text)
    (HERE / "RESULTS_temporal_graph.md").write_text("<!-- generated by tg_report.py from results_narrative_temporal_graph.md and the result JSONs; do not edit by hand -->\n" + text); print("written")
