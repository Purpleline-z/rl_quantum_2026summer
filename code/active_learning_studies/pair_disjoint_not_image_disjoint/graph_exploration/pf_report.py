"""Builds RESULTS_physics_features.md: the hand-written narrative (results_narrative_physics_features.md) with every {{TABLE:name}} replaced by a table generated from result files.
  python3 -W ignore pf_report.py     (run from this directory; tables whose result directory does not exist are marked 'not run')"""
import json, re
from pathlib import Path
import pandas as pd
import pf_tables as T

HERE = Path(__file__).resolve().parent; NEW = HERE.parents[1] / "new_directions"; RES = NEW / "results" / "pf"


def have(*names): return all((RES / n).is_dir() and any((RES / n).glob("seed*.csv.gz")) for n in names)


def read(name):
    f = RES / name; return f.read_text() if f.exists() else f"*{name}: not generated*"


def dev(dirs, ref="lap3_k10_st4", only=None):
    ds = [d for d in dirs if have(d)]
    if not ds: return "*not run*"
    fr = T.load([RES / d for d in ds]); t = T.dev_table(fr, ref, only); return T.to_md(t)


def spec(name): return json.loads((HERE / name).read_text())


def confirm(name, which, sp="PF1_spec.json", dirs=None):
    s = spec(sp); ds = dirs or [name]
    if not have(*ds): return f"*{name}: not run*"
    out, ver = T.confirm_tables(s, T.load([RES / d for d in ds])); cols = ["family", "split", "metric", "cells", "n", "gain", "lo", "hi", "share", "p", "holm"]
    if which == "verdict": return T.to_md(ver, "{:+.4f}")
    sel = {"main": out[out.family == "main"], "far": out[out.family.isin(["far", "far_split"])], "controls": out[out.family.str.startswith("control")], "secondary": out[out.family == "secondary"], "reference": out[out.family.isin(["vs_graphfree", "baseline_vs_graphfree"])]}[which]
    return T.to_md(sel[cols].astype({c: float for c in ("gain", "lo", "hi", "share", "p", "holm")})) if len(sel) else "*none*"


TABLES = {
    "ideal_cv": lambda: read("ideal_cv_v2.md"), "ideal_cv_paired": lambda: read("ideal_cv_v2_paired.md"), "zeroshot": lambda: read("zeroshot.md"), "graph_stats": lambda: read("graph_stats.md"), "plugin": lambda: read("plugin_dev.md"),
    "dev_A": lambda: dev(["devA"]), "dev_B1": lambda: dev(["devB1"]), "dev_B2": lambda: dev(["devB2"]), "dev_B3": lambda: dev(["devB3"]),
}


def table(name):
    if name in TABLES: return TABLES[name]()
    m = re.fullmatch(r"(confirm1|confirm2|blocked)_(main|far|controls|secondary|reference|verdict)", name)
    if m: return confirm(m.group(1), m.group(2), dirs=[m.group(1)] + (["confirm1_controls"] if m.group(1) == "confirm1" and have("confirm1_controls") else []))
    raise KeyError(name)


if __name__ == "__main__":
    text = (HERE / "results_narrative_physics_features.md").read_text(); text = re.sub(r"\{\{TABLE:([A-Za-z0-9_]+)\}\}", lambda mo: table(mo.group(1)), text)
    (HERE / "RESULTS_physics_features.md").write_text("<!-- generated by pf_report.py from results_narrative_physics_features.md and the result files; do not edit by hand -->\n" + text); print("written")
