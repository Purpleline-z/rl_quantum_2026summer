"""Builds RESULTS_graph_learner.md: the hand-written narrative (results_narrative_graph_learner.md) with every {{TABLE:name}} replaced by a table generated from the result JSONs.
  python3 gl_report.py        (run from this directory; tables whose result directory does not exist yet are marked 'not run')"""
import json, re, sys
from pathlib import Path
import pandas as pd
import gl_tables as T

HERE = Path(__file__).resolve().parent; RES = HERE.parents[1] / "new_directions" / "results" / "gl"
spec = json.loads((HERE / "G1_spec.json").read_text()); cands = spec["candidates"]
ctls = [spec["controls"][c]["shuf"] for c in cands]; noise = [spec["controls"][c]["noise3"] for c in cands if "noise3" in spec["controls"][c]]


def have(*names): return all((RES / n).is_dir() and any((RES / n).glob("seed*.json")) for n in names)


def dev_frame(): return T.load([RES / n for n in ("dev1", "dev2", "dev3") if (RES / n).is_dir()])


def table(name: str) -> str:
    if name == "dev_all":
        f = dev_frame(); t = T.dev_table(f); t = t[[c for c in t.columns if not c.endswith("_lo") and not c.endswith("_hi")]]; return T.to_md(t)
    if name == "dev_selected":
        f = dev_frame(); t = T.dev_table(f); t = t[t.learner.isin(cands + ctls + noise)][["split", "learner", "auc", "acc", "ll", "htr_acc", "htr_ll", "n"]]; return T.to_md(t)
    if name == "dev_cold":
        f = T.load([RES / "dev_cold"]); t = T.dev_table(f); t = t[["split", "learner", "auc", "acc", "ll", "htr_acc", "htr_ll", "n"]]; return T.to_md(t)
    if name == "dev_budget": return T.to_md(T.budget_table(dev_frame(), cands))
    if name == "dev_types": return T.to_md(T.type_table(dev_frame(), cands))
    if name == "mechanism": return (HERE / "mechanism_graph_learner.md").read_text()
    m = re.match(r"(confirm1|confirm2|cold)_(main|verdict|budget|types)$", name)
    if m:
        exp, kind = m.groups()
        if not have(exp): return f"*{exp}: not run*"
        if kind in ("main", "verdict"):
            out, md = T.confirm_report(spec, [RES / exp]); return md if kind == "main" else T.to_md(T.verdicts(out, spec), "{}")
        f = T.load([RES / exp]); learners = cands + ctls
        return T.to_md(T.budget_table(f, learners) if kind == "budget" else T.type_table(f, learners))
    raise KeyError(name)


if __name__ == "__main__":
    text = (HERE / "results_narrative_graph_learner.md").read_text()
    text = re.sub(r"\{\{TABLE:([a-z0-9_]+)\}\}", lambda mo: table(mo.group(1)), text)
    (HERE / "RESULTS_graph_learner.md").write_text("<!-- generated by gl_report.py from results_narrative_graph_learner.md and the result JSONs; do not edit by hand -->\n" + text); print("written")
