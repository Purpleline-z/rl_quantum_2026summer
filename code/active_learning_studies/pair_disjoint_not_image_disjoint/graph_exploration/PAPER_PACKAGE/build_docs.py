"""Resolves {{INCLUDE:path}} (path relative to PAPER_PACKAGE) in the checked prose documents of build/ and writes the delivery copies:
  graph_exploration/RESULTS_paper_package.md      (results_head: claims table, abstract, figures, assumptions and limits)
  graph_exploration/SUMMARY_ZH_paper_package.md   (one-page Chinese summary)
  graph_exploration/HANDOFF_paper_package.md, GPU_TASKS_paper_package.md
  PAPER_PACKAGE/ABSTRACT_EN.md, PAPER_PACKAGE/ADVISOR_SUMMARY_ZH.md
Run after check_prose.py (which strips the markers into build/)."""
import re

import pp_lib as L

INC = re.compile(r"\{\{INCLUDE:([^}]+)\}\}")


def resolve(text):
    while INC.search(text): text = INC.sub(lambda m: (L.PKG / m.group(1)).read_text().rstrip() + "\n", text)   # includes may be nested (build/*.md contain further includes)
    return text


def main():
    out = {"results_head": L.GE / "RESULTS_paper_package.md", "summary_ZH": L.GE / "SUMMARY_ZH_paper_package.md", "handoff": L.GE / "HANDOFF_paper_package.md", "gpu_tasks": L.GE / "GPU_TASKS_paper_package.md", "abstract_EN": L.PKG / "ABSTRACT_EN.md", "README": L.PKG / "README.md"}
    for name, dest in out.items():
        src = L.BUILD / f"{name}.md"
        if not src.exists(): print("missing", src); continue
        text = resolve(src.read_text()); tag = "<!-- generated by build_docs.py from PAPER_PACKAGE/prose/%s.src.md and the generated tables; do not edit by hand -->\n" % name
        dest.write_text(tag + text); print("wrote", dest.relative_to(L.GE.parent))
    (L.PKG / "ADVISOR_SUMMARY_ZH.md").write_text((L.BUILD / "summary_ZH.md").read_text()); print("wrote PAPER_PACKAGE/ADVISOR_SUMMARY_ZH.md")


if __name__ == "__main__":
    main()
