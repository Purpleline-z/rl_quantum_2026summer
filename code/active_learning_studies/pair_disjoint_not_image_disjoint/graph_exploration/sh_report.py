"""Builds RESULTS_selection_htr.md: the hand-written narrative (results_narrative_selection_htr.md) with every {{TABLE:name}} replaced by a table generated from the result JSONs.
  python3 sh_report.py      (run from this directory; tables whose result directory does not exist yet are marked 'not run')"""
import json, re
from pathlib import Path
import pandas as pd
import sh_tables as T

HERE = Path(__file__).resolve().parent; RES = HERE.parents[1] / "new_directions" / "results" / "sh"


def have(name): return (RES / name).is_dir() and any((RES / name).glob("seed*.json"))


def dirs(*names): return [RES / n for n in names if (RES / n).is_dir()]


def learners_table(ref, selector="random"):
    f = T.load(dirs("sdev1", "sdev3", "sdev4", "sdev5", "sdev6")); rows = []
    for split in sorted(f.split.unique()):
        for l in sorted(set(f[(f.split == split) & (f.selector == selector)].learner) - {ref}):
            r = {"split": split, "learner": l}
            for m in ("auc", "acc", "ll", "htr_acc", "htr_ll", "t1x1_acc", "tc6x2_acc", "t13_acc"):
                try: o = T.summarize(T.gain(f, split, m, (selector, l), (selector, ref))); r[m] = o["gain"]; r["n_seeds"] = o["n"]
                except Exception: pass
            rows.append(r)
    return T.to_md(pd.DataFrame(rows))


def table(name: str) -> str:
    if name == "dev_sel_lap3":
        t = T.dev_table(T.load(dirs("sdev1", "sdev2")), "lap3_k10"); return T.to_md(t[[c for c in t.columns if not c.endswith("_holm")]])
    if name == "dev_sel_aw8": t = T.dev_table(T.load(dirs("sdev1")), "aw8_all"); return T.to_md(t[[c for c in t.columns if not c.endswith("_holm")]])
    if name == "dev_types":
        t = T.dev_table(T.load(dirs("sdev1", "sdev2")), "lap3_k10", metrics=("t1x1_acc", "tc6x2_acc", "t13_acc", "htr_acc", "htr_ll")); return T.to_md(t[[c for c in t.columns if not c.endswith("_p") and not c.endswith("_holm")]])
    if name == "dev_comp":
        t = T.comp_table(T.load(dirs("sdev1", "sdev2")), "lap3_k10"); return T.to_md(t[t.selector.isin(["random", "vopt_u", "vopt_htr2", "vopt_htr4", "gvopt_node3", "vopt_bridge3"])], "{:.1f}")
    if name == "dev_learners_lap": return learners_table("lap3_k10")
    if name == "dev_learners_aw8": return learners_table("aw8_all")
    if name == "dev_learners_st4": return learners_table("lap3_k10_st4")
    if name == "dev_selection_st4":
        return T.to_md(T.dev_table(T.load(dirs("sdev7")), "lap3_k10_st4")) if have("sdev7") else "*sdev7: not run*"
    m = re.match(r"(c1|c2)_(sel|learn|sel4)$", name)
    if m:
        exp = name
        if not have(exp): return f"*{exp}: not run*"
        spec_file = {"sel": "SH1_spec_select.json", "learn": "SH1_spec_learner.json", "sel4": "SH1_spec_select_st4.json"}[m.group(2)]; spec = json.loads((HERE / spec_file).read_text())
        out, md = T.confirm_report(spec, [RES / exp]); v = (T.verdicts_learner if "references" in spec else T.verdicts)(out, spec)
        return md + "\n\nVerdicts by the pre-registered rule:\n\n" + T.to_md(v, "{}")
    raise KeyError(name)


if __name__ == "__main__":
    text = (HERE / "results_narrative_selection_htr.md").read_text()
    text = re.sub(r"\{\{TABLE:([a-z0-9_]+)\}\}", lambda mo: table(mo.group(1)), text)
    (HERE / "RESULTS_selection_htr.md").write_text("<!-- generated by sh_report.py from results_narrative_selection_htr.md and the result JSONs; do not edit by hand -->\n" + text); print("written")
