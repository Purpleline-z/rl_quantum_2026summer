"""Builds RESULTS_representation.md: the hand-written narrative (results_narrative_representation.md) with every {{TABLE:name}} replaced by a table generated from the result JSONs.
  python3 -W ignore rp_report.py      (run from this directory)"""
import json, re
from pathlib import Path
import pandas as pd
import gl_tables as gt
import rp_tables as rt

HERE = Path(__file__).resolve().parent; RES = HERE.parents[1] / "new_directions" / "results" / "rp"
spec = json.loads((HERE / "R1_spec.json").read_text()); cands = list(spec["candidates"]); REF, GF = spec["reference"], spec["graphfree"]


def have(n): return (RES / n).is_dir() and any((RES / n).glob("seed*.json"))


def dev(refs, dirs, only=None):
    f = rt.load_complete([RES / d for d in dirs]); t = gt.dev_table(f, refs, metrics=("auc", "acc", "ll", "htr_acc", "htr_ll")); t = t[[c for c in t.columns if not c.endswith(("_lo", "_hi", "_vs_ctl", "_vs_ctl_p"))]]
    return t[t.learner.isin(only)] if only else t


def table(name: str) -> str:
    if name == "dev_stageA": return gt.to_md(dev(REF, ["devA"]))
    if name == "dev_stageB1": return gt.to_md(dev("rp_gf_s4", ["devB1"]))
    if name == "dev_lr":
        t = dev(REF, ["devB2"]); return gt.to_md(t) + "\n\n(reference = `lap3_k10_st4` on the same complete seeds; the table lists only seeds whose cell files are complete)"
    if name == "dev_ens": return (HERE / "rp_ens_table.md").read_text()
    if name == "dev_budget": return gt.to_md(gt.budget_table(rt.load_complete([RES / "devA"]), cands, REF))
    if name == "dev_types": return gt.to_md(gt.type_table(rt.load_complete([RES / "devA"]), cands, REF))
    if name == "dev_H":
        if not (have("devH1") and have("devH2")): return "*devH: not run*"
        f = rt.load_complete([RES / d for d in ("devA", "devH1", "devH2")]); rows = []
        for a, b in (("rp_gs4_his", REF), ("rp_gs4_his_shuf", REF), ("rp_cap", REF), ("rp_gs4_his", "rp_gs4_his_shuf"), ("rp_gs4_his", "rp_cap")):
            for split in ("A", "B"):
                for m in ("auc", "acc", "ll", "htr_acc", "htr_ll", "t13_acc"):
                    s = gt.summarize(gt.gain(f, split, m, a, b)); rows.append({"pair": f"{a} - {b}", "split": split, "metric": m, "gain": s["gain"], "lo": s["lo"], "hi": s["hi"], "share_better": s["share"], "p_uncorrected": s["p"], "n_seeds": s["n"]})
        return gt.to_md(pd.DataFrame(rows))
    if not have("confirm1"): return "*confirm1: not run*"
    f = rt.load_complete([RES / "confirm1"]); out, ver = rt.confirm_tables(spec, f)
    if name == "confirm_n": return f"{f.seed.nunique()} seeds; learners: {sorted(set(f.learner))}"
    cols = ["family", "split", "metric", "cells", "n_seeds", "gain", "lo", "hi", "share_better", "p", "holm"]
    def md(sel): return gt.to_md(sel[cols].assign(**{k: sel[k].astype(float) for k in ("gain", "lo", "hi", "share_better", "p", "holm")}))
    if name == "confirm_main": return md(out[out.family == "main"])
    if name == "confirm_verdict": return gt.to_md(ver, "{}")
    if name == "confirm_secondary": return md(out[out.family.str.startswith("secondary")])
    if name == "confirm_graphfree": return md(out[out.family.isin(["vs_graphfree", "baseline_vs_graphfree"])])
    if name == "confirm_controls":
        s = out[out.family.str.startswith("control")]; return md(s) if len(s) else "*controls not run (no candidate had positive AUC and accuracy differences in both splits)*"
    if name == "confirm_budget": return gt.to_md(gt.budget_table(f, cands, REF))
    if name == "confirm_types": return gt.to_md(gt.type_table(f, cands + [GF], REF))
    if name == "confirm_ranges":
        rows = []
        for cand in cands:
            for split in spec["splits"]:
                for m in ("auc", "acc"):
                    s = gt.summarize(gt.gain(f, split, m, cand, REF)); rows.append({"candidate": cand, "split": split, "metric": m, "gain": s["gain"], "lo": s["lo"], "hi": s["hi"], "n": s["n"]})
        return gt.to_md(pd.DataFrame(rows))
    raise KeyError(name)


if __name__ == "__main__":
    text = (HERE / "results_narrative_representation.md").read_text()
    text = re.sub(r"\{\{TABLE:([A-Za-z0-9_]+)\}\}", lambda mo: table(mo.group(1)), text)
    (HERE / "RESULTS_representation.md").write_text("<!-- generated by rp_report.py from results_narrative_representation.md and the result JSONs; do not edit by hand -->\n" + text); print("written")
