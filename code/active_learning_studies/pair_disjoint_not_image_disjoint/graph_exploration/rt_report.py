"""Builds RESULTS_redteam.md from results_narrative_redteam.md: every {{TABLE:name}} is replaced by a table generated from the result files (nothing typed by hand).  Run from this directory."""
import io, re, subprocess, sys, contextlib
from pathlib import Path
import pandas as pd
import rt_tables as T
import rt_confirm as C

HERE = Path(__file__).resolve().parent; RES = HERE.parents[1] / "new_directions" / "results" / "rt"


def have(n): return (RES / n).is_dir() and any(RES.joinpath(n).iterdir())


def pairs_auc(a1, a1b, pairs):
    df, b = T.load_a1(RES / a1), T.load_a1b(RES / a1b); out = []
    for cand, ref in pairs:
        t = T.auc_by_stratum(df, b, cand, ref, [("all", -1, 9), ("anchor-near (<=0.001)", -1, 0.001), ("0.001-0.01", 0.001, 0.01), ("0.01-0.03", 0.01, 0.03), ("anchor-far (>0.03)", 0.03, 9), ("far from anchors (>0.01)", 0.01, 9)])
        t.insert(0, "cand - ref", f"{cand} - {ref}"); out.append(t)
    return T.to_md(pd.concat(out))


def table(name):
    if name == "a6": return (RES / "a6.md").read_text()
    if name == "a7": return (RES / "a7.md").read_text()
    if name == "a1_nov": return "\n\n".join(f"**{c} - {r}**\n\n" + T.to_md(T.stratified(T.per_judgment(T.load_a1(RES / "a1"), c, r), "nov_train_max", 4)) for c, r in (("lap3_k10_st4", "aw8_all_st2lr0.5"), ("lap3_k10_st4", "aw8_all")))
    if name == "a1_anchor_acc": return "\n\n".join(f"**{c} - {r}**\n\n" + T.to_md(T.stratified_custom(T.anchor_bins(T.per_judgment(T.load_a1(RES / "a1"), c, r).merge(T.load_a1b(RES / "a1b"), on=["seed", "split", "j"]), "anc_all_min"))) for c, r in (("lap3_k10_st4", "aw8_all_st2lr0.5"),))
    if name == "a1_anchor_auc": return pairs_auc("a1", "a1b", [("lap3_k10_st4", "aw8_all_st2lr0.5"), ("lap3_k10_st4", "aw8_all"), ("lap3_k10", "aw8_all"), ("lap3_k10_st4", "lap3_k10"), ("aw8_all_st2lr0.5", "aw8_all")])
    if name == "a1c_anchor_auc": return pairs_auc("a1c", "a1b", [("aw8_all", "baseline"), ("aw8", "baseline"), ("aw8_all", "aw8")])
    if name == "a8":
        buf = io.StringIO(); sys.argv = ["rt_tables.py", "a8", str(RES / "a1")]
        with contextlib.redirect_stdout(buf): exec(compile((HERE / "rt_tables.py").read_text(), "rt_tables", "exec"), {"__name__": "__main__", "__file__": str(HERE / "rt_tables.py")})
        return buf.getvalue()
    if name in ("a2", "a3"):
        if not have(name): return f"*{name}: not run*"
        df = T.load_json_dir(RES / name); cols = ("split", "delta") if name == "a2" else ("split",); parts = []
        for c, r in (("lap3_k10_st4", "aw8_all_st2lr0.5"), ("lap3_k10", "aw8_all_st2lr0.5"), ("lap3_k10_st4", "lap3_k10")) + ((("lap3_k10_st4", "lap3_k10_st4_shuf"),) if name == "a3" else ()):
            t = T.gain_table(df, c, r, cols)
            if len(t): parts.append(f"**{c} - {r}**\n\n" + T.to_md(t[[x for x in t.columns if not x.endswith(("_lo", "_hi"))]]))
        extra = ""
        if name == "a2": extra = "\n\nGraph nodes kept (mean) by delta:\n\n" + T.to_md(df.groupby(["split", "delta"]).n_nodes.mean().reset_index(), "{:.0f}")
        if name == "a3":
            ex = df[df.learner == "lap3_k10_st4"].groupby("seed")[["n_test", "n_test_groups", "n_pool_groups", "n_zone_images", "nov_train_max_median"]].mean(); extra = "\n\nBlocked-split sizes (mean over seeds): " + ", ".join(f"{k} = {v:.3g}" for k, v in ex.mean().items())
        return "\n\n".join(parts) + extra
    if name == "a4":
        if not have("a4"): return "*a4: not run*"
        buf = io.StringIO(); sys.argv = ["rt_tables.py", "a4", str(RES / "a4"), str(RES / "a1")]
        with contextlib.redirect_stdout(buf): exec(compile((HERE / "rt_tables.py").read_text(), "rt_tables", "exec"), {"__name__": "__main__", "__file__": str(HERE / "rt_tables.py")})
        return buf.getvalue()
    if name == "a5":
        if not have("a5"): return "*a5: not run*"
        buf = io.StringIO(); sys.argv = ["rt_tables.py", "a5", str(RES / "a5")]
        with contextlib.redirect_stdout(buf): exec(compile((HERE / "rt_tables.py").read_text(), "rt_tables", "exec"), {"__name__": "__main__", "__file__": str(HERE / "rt_tables.py")})
        return buf.getvalue()
    if name == "confirm":
        if not all(have(n) for n in ("c_a1", "c_a1b", "c_a3", "c_a2")): return "*confirmation not (fully) run*"
        out = C.run(*(str(RES / n) for n in ("c_a1", "c_a1b", "c_a3", "c_a2"))); return C.md(out) + "\n\nVerdicts by the pre-registered rule:\n\n" + C.md(C.verdicts(out), "{}")
    raise KeyError(name)


if __name__ == "__main__":
    text = (HERE / "results_narrative_redteam.md").read_text(); text = re.sub(r"\{\{TABLE:([a-z0-9_]+)\}\}", lambda m: table(m.group(1)), text)
    (HERE / "RESULTS_redteam.md").write_text("<!-- generated by rt_report.py from results_narrative_redteam.md and the result files; do not edit by hand -->\n" + text); print("written")
