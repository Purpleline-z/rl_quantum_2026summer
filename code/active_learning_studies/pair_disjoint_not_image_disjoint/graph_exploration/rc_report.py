"""Assembles RESULTS_recipe.md from results_narrative_recipe.md ({{TABLE:name}} placeholders) and the result JSONs.  Nothing in a table is typed by hand.

  python3 rc_report.py [--template results_narrative_recipe.md] [--doc RESULTS_recipe.md]

Placeholders: variants, dev_t1, dev_t1_full, dev_t2, dev_types, dev_strata, dev_budget, dev_counts, confirm (whole generated confirmation section; needs FROZEN below).
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import fields
from pathlib import Path

import numpy as np
import pandas as pd

import rc_confirm
import rc_tables as T

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(T.NEW))
import nd_recipe as R  # noqa: E402

REF, CONTROL = "lap3_k10_st4", "aw8_all_st2lr0.5"
DEV = [str(T.NEW / "results/rc/dev1"), str(T.NEW / "results/rc/dev2")]
CONF = [str(T.NEW / "results/rc/conf")]
FROZEN = json.loads((HERE / "RC1_spec.json").read_text()) if (HERE / "RC1_spec.json").exists() else None


def variants_table() -> str:
    run = T.load(DEV); seen = run.groupby("learner").seed.nunique().to_dict(); rows = []
    for name, spec in R.VARIANTS.items():
        if name == "rc_base": continue
        diff = {f.name: getattr(spec, f.name) for f in fields(R.Spec) if getattr(spec, f.name) != getattr(R.BASE, f.name)}
        rows.append({"variant": name, "switch (vs incumbent)": ", ".join(f"{k}={v}" for k, v in diff.items()), "development seeds run": seen.get(name, 0) or "not screened (12-variant budget)"})
    for name in sorted(l for l in seen if l.startswith("rcx_")): rows.append({"variant": name, "switch (vs incumbent)": "combination of " + name[4:].replace("+", " and "), "development seeds run": seen[name]})
    return T.md(pd.DataFrame(rows), fmt=".0f")


def with_score(sv: pd.DataFrame) -> pd.DataFrame:
    sv = sv.copy(); sv["score"] = (sv.auc_A + sv.auc_B + sv.acc_A + sv.acc_B) / 4
    return sv.sort_values("score", ascending=False).reset_index(drop=True)


def dev_frames():
    df = T.load(DEV); n1 = T.load([DEV[0]]); return df, n1


def table(name: str) -> str:
    df, n1 = dev_frames()
    if name == "variants": return variants_table()
    if name == "dev_counts": return T.md(df.groupby(["learner", "split"]).agg(seeds=("seed", "nunique"), cells=("auc", "size")).reset_index(), fmt=".0f")
    if name == "dev_t1":   # tier 1: seeds 9300-9309 only, all learners
        tab = T.dev_table(n1, REF); return T.md(with_score(T.shortlist_view(tab))[["learner", "n_seeds", "auc_A", "auc_B", "acc_A", "acc_B", "score", "ll_A", "ll_B", "far_auc_A", "far_auc_B", "far_acc_A", "far_acc_B", "htr_acc_A", "htr_acc_B"]])
    if name == "dev_t1_full": return T.md(T.dev_table(n1, REF))
    if name == "dev_t2":   # all 20 development seeds (learners that were extended)
        ext = df.groupby("learner").seed.nunique(); ext = [l for l in ext[ext >= 20].index if l != REF]
        tab = T.dev_table(df[df.learner.isin(ext + [REF])], REF); sv = with_score(T.shortlist_view(tab))
        return T.md(sv[["learner", "n_seeds", "auc_A", "auc_B", "acc_A", "acc_B", "score", "all_positive", "holm<0.05 (of 4)", "ll_A", "ll_B", "far_auc_A", "far_auc_B", "far_acc_A", "far_acc_B", "htr_acc_A", "htr_acc_B"]]) + "\n\nFull rows (with intervals and Holm values):\n\n" + T.md(tab)
    if name == "dev_mde": return T.md(T.mde_table(n1[~n1.learner.isin(["rc_do0.3", CONTROL])], REF))
    if name == "dev_types": return T.md(T.types_table(n1, REF))
    if name == "dev_strata": return T.md(T.strata_table(T.load([DEV[0]], keep_d=True), REF))
    if name == "dev_budget":
        rows = []
        for l in sorted(n1.learner.unique()):
            if l == REF: continue
            for split in ("A", "B"):
                row = {"learner": l, "split": split}
                for b in (10, 20, 40, 60):
                    sub = n1[n1.budget == b]; row[f"auc@{b}"] = T.summarize(T.per_seed_gain(sub, l, REF, split, "auc"))["gain"]
                rows.append(row)
        return T.md(pd.DataFrame(rows))
    if name == "confirm":
        if FROZEN is None: return "(confirmation not yet run)"
        return rc_confirm.run(CONF, REF, FROZEN["candidates"], CONTROL)
    raise KeyError(name)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__); ap.add_argument("--template", type=Path, default=HERE / "results_narrative_recipe.md"); ap.add_argument("--doc", type=Path, default=HERE / "RESULTS_recipe.md")
    a = ap.parse_args(); text = a.template.read_text()
    out = re.sub(r"\{\{TABLE:(\w+)\}\}", lambda m: table(m.group(1)), text)
    a.doc.write_text("<!-- generated by rc_report.py from results_narrative_recipe.md and the result JSONs; do not edit by hand -->\n" + out)


if __name__ == "__main__": main()
