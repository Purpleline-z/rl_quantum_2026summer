"""Assembles RESULTS_score_propagation.md from results_narrative_score_propagation.md ({{TABLE:name}} placeholders) and the result JSONs.  Nothing in a table is typed by hand.

  python3 sp_report.py [--template results_narrative_score_propagation.md] [--doc RESULTS_score_propagation.md]
Placeholders: variants, dev_counts, dev_all (tier 1: every variant, seeds 11200-11209 where run), dev_ext (variants run on all 20 development seeds), dev_types, dev_strata, dev_mde, offline_scan, offline_strata,
dev_blocked, dev_cold, confirm1, confirm2.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import numpy as np
import pandas as pd

import rc_tables as T
import sp_confirm
import sp_offline

HERE = Path(__file__).resolve().parent
RES = T.NEW / "results" / "sp"
REF, CONTROL = "lap3_k10_st4", "aw8_all_st2lr0.5"
SPEC = json.loads((HERE / "SP1_spec.json").read_text()) if (HERE / "SP1_spec.json").exists() else None


def d(*names): return [str(RES / n) for n in names if (RES / n).exists()]


def score_view(df: pd.DataFrame, ref=REF) -> pd.DataFrame:
    tab = T.dev_table(df, ref); sv = T.shortlist_view(tab); sv["score"] = (sv.auc_A + sv.auc_B + sv.acc_A + sv.acc_B) / 4
    return sv.sort_values("score", ascending=False).reset_index(drop=True)


COLS = ["learner", "n_seeds", "auc_A", "auc_B", "acc_A", "acc_B", "score", "ll_A", "ll_B", "far_auc_A", "far_auc_B", "far_acc_A", "far_acc_B", "htr_acc_A", "htr_acc_B"]


def table(name: str) -> str:
    if name == "dev_counts":
        df = T.load(d("dev1", "dev2")); return T.md(df.groupby(["learner", "split"]).agg(seeds=("seed", "nunique"), cells=("auc", "size")).reset_index(), fmt=".0f")
    if name == "variants":
        df = T.load(d("dev1", "dev2")); seen = df.groupby("learner").seed.nunique(); return T.md(pd.DataFrame({"variant": seen.index, "development seeds run": seen.values}).sort_values("variant"), fmt=".0f")
    if name == "dev_all": return T.md(score_view(T.load(d("dev1")))[COLS])
    if name == "dev_ext":
        df = T.load(d("dev1", "dev2")); n = df.groupby("learner").seed.nunique(); keep = [l for l in n[n >= 20].index]
        sv = score_view(df[df.learner.isin(keep)]); return T.md(sv[COLS]) + "\n\nFull rows (intervals and Holm values over the learners shown):\n\n" + T.md(T.dev_table(df[df.learner.isin(keep)], REF))
    if name == "dev_types": return T.md(T.types_table(T.load(d("dev1")), REF))
    if name == "dev_strata": return T.md(T.strata_table(T.load(d("dev1"), keep_d=True), REF))
    if name == "dev_mde": return T.md(T.mde_table(T.load(d("dev1")), REF, [l for l in T.load(d("dev1")).learner.unique() if l.startswith(("rt_", "fs_lam10"))]))
    if name == "offline_scan": return T.md(sp_offline.scan(d("dev1", "dev2")).head(16))
    if name == "offline_strata": return T.md(sp_offline.strata(d("dev1", "dev2"), "fs_lam10_rho0.001", 2.0))
    if name in ("dev_blocked", "dev_cold"):
        dd = d("dev_blocked" if name == "dev_blocked" else "dev_cold")
        if not dd: return "(not run)"
        df = T.load(dd); spl = ("blocked",) if name == "dev_blocked" else ("A", "B"); tab = sp_confirm.family(df, REF, [l for l in sorted(df.learner.unique()) if l != REF], ("auc", "acc", "ll", "far_auc", "far_acc", "htr_acc"), splits=spl)
        return T.md(tab.drop(columns=["holm"], errors="ignore"))
    if name in ("confirm1", "confirm2"):
        if SPEC is None: return "(confirmation not yet run)"
        key = "conf1" if name == "confirm1" else "conf2"; dirs = d(key, f"{key}_ctl"); blocked = d(f"{key}_blocked"); cold = d(f"{key}_cold")
        if not dirs: return "(not run)"
        return sp_confirm.run(SPEC, dirs, blocked or None, cold or None)
    raise KeyError(name)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__); ap.add_argument("--template", type=Path, default=HERE / "results_narrative_score_propagation.md"); ap.add_argument("--doc", type=Path, default=HERE / "RESULTS_score_propagation.md")
    a = ap.parse_args(); out = re.sub(r"\{\{TABLE:(\w+)\}\}", lambda m: table(m.group(1)), a.template.read_text())
    a.doc.write_text("<!-- generated by sp_report.py from results_narrative_score_propagation.md and the result JSONs; do not edit by hand -->\n" + out)


if __name__ == "__main__": main()
