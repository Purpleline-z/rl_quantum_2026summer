"""Latent-type model (branch claude/latent-type-1014): Dawid-Skene-style latent-class model of the judgment-generating process.

Every image i carries a latent type z_i in {0,1,2,3} = the four reconstruction types ((1x1), c(6x2), RT13, HTR; column order = ``nd_graph_learner.ACTIVE``) or the extra state 4 = "none of the four".
A labelled judgment (image a, image b, type k, outcome o in {a wins, b wins, tie, not_apply}) is generated by

    P(o | z_a, z_b, k) = T[s_a, s_b, o],   s_x = 1[z_x == k]

with swap symmetry (a decisive win for the typed image has the same probability whichever side it is on) and confusion parameters shared across the four types (``pool``) and learned by EM:
  both images of type k  : [decisive (split evenly), tie, not_apply]
  neither image of type k: [decisive (split evenly), tie, not_apply]
  exactly one of type k  : [typed image wins, other wins, tie, not_apply]
Prior over z_i: the label-spreading posterior q_i of the typed ideal images over the cosine kNN graph (``GraphData.q``), mixed with a floor and an "other" mass rho.  Judgments of the same image pair for several types
are one pairwise factor (so a not_apply for type k together with a tie for type k' constrains the same pair of latent types).  E-step: loopy sum-product belief propagation over the (small) image graph of the
labelled judgments; M-step: expected counts + Dirichlet pseudo-counts.  The pseudo-counts only encode the verbal definition of the outcomes (not_apply: at least one image is not of type k; tie: equally type k;
decisive: which is more type k), never the data.

Controls (``mode``): 'em' full model; 'prior' = no outcome likelihood (posterior = prior; graph prior only); 'random' = the EM posteriors reassigned at random among the same images (same confidence distribution,
no information); the shuffled prior is obtained by building q on the shuffled graph (done by the caller).
"""
from __future__ import annotations

import numpy as np

import nd_graph_learner as G

NT = 4; NS = 5                      # latent states: 4 types + "none"
OUT = {"1": 0, "2": 1, "tie": 2, "not_apply": 3}
COL = {0: 0, 2: 1, 3: 2, 4: 3}      # type_idx -> latent / posterior column
# Dirichlet pseudo-counts that encode the outcome definitions ([both of type k], [typed wins, other wins, tie, na], [neither])
PRIOR_COUNTS = {"11": np.array([2.0, 2.0, 0.5]), "10": np.array([2.0, 0.3, 0.5, 2.0]), "00": np.array([0.5, 0.5, 3.0])}


def build_table(p11, p10, p00) -> np.ndarray:
    """T[s_a, s_b, o] from the three parameter vectors."""
    t = np.zeros((2, 2, 4)); t[1, 1] = [p11[0] / 2, p11[0] / 2, p11[1], p11[2]]; t[0, 0] = [p00[0] / 2, p00[0] / 2, p00[1], p00[2]]
    t[1, 0] = [p10[0], p10[1], p10[2], p10[3]]; t[0, 1] = [p10[1], p10[0], p10[2], p10[3]]; return t


def init_table(scale: float = 1.0) -> np.ndarray:
    return build_table(*(PRIOR_COUNTS[k] * scale / (PRIOR_COUNTS[k] * scale).sum() for k in ("11", "10", "00")))


def prior_from_q(q: np.ndarray, rho: float = 0.15, floor: float = 0.05) -> np.ndarray:
    """(n, 4) label-spreading posterior -> (n, 5) prior with a floor and 'none' mass rho."""
    p = (1 - floor) * q + floor / NT; p = p * (1 - rho); return np.concatenate([p, np.full((len(p), 1), rho)], 1)


class Judgments:
    """Pairwise factors of a set of labelled judgments: unique image pairs (ordered as first seen), each with its (type column, outcome) list."""
    def __init__(self, rows):
        self.images: list[str] = []; self.index: dict[str, int] = {}; self.factors: dict[tuple[int, int], list[tuple[int, int]]] = {}; self.rows = []
        for r in rows.itertuples():
            ia, ib = (self._id(str(r.resolved_img1)), self._id(str(r.resolved_img2))); k, o = COL[int(r.type_idx)], OUT[r.Winner]
            if ia == ib: self.rows.append((ia, ib, k, o, None)); continue
            key, flip = ((ia, ib), False) if ia < ib else ((ib, ia), True)
            if flip: o = {0: 1, 1: 0, 2: 2, 3: 3}[o]
            self.factors.setdefault(key, []).append((k, o)); self.rows.append((ia, ib, k, OUT[r.Winner], key))

    def _id(self, p: str) -> int:
        if p not in self.index: self.index[p] = len(self.images); self.images.append(p)
        return self.index[p]


def _state_masks() -> np.ndarray:
    """S[k, z] = 1 if z == k (z in 0..4)."""
    s = np.zeros((NT, NS)); s[np.arange(NT), np.arange(NT)] = 1; return s


S = _state_masks()


def factor_potential(items, table) -> np.ndarray:
    """psi(z_a, z_b) of one pair: product over its (k, o) of T[s_k(z_a), s_k(z_b), o]."""
    psi = np.ones((NS, NS))
    for k, o in items:
        sa = S[k].astype(int)[:, None]; sb = S[k].astype(int)[None, :]; psi = psi * table[sa, sb, o]
    return psi


def belief_propagation(prior: np.ndarray, fac: dict, table: np.ndarray, iters: int = 20, damping: float = 0.5):
    """Loopy sum-product.  Returns node beliefs (n, 5) and pair beliefs {key: (5, 5)}."""
    n = len(prior); psi = {key: factor_potential(items, table) for key, items in fac.items()}
    m_f2a = {key: np.ones(NS) / NS for key in fac}; m_f2b = {key: np.ones(NS) / NS for key in fac}      # messages factor -> variable a / b
    inc = [[] for _ in range(n)]
    for key in fac: inc[key[0]].append((key, 0)); inc[key[1]].append((key, 1))
    def node_prod(i, skip=None):
        v = prior[i].copy()
        for key, side in inc[i]:
            if (key, side) == skip: continue
            v = v * (m_f2a[key] if side == 0 else m_f2b[key])
        return v / v.sum()
    for _ in range(iters):
        new_a, new_b = {}, {}
        for key in fac:
            a, b = key; va = node_prod(a, (key, 0)); vb = node_prod(b, (key, 1))
            ma = psi[key] @ vb; mb = psi[key].T @ va; new_a[key] = ma / ma.sum(); new_b[key] = mb / mb.sum()
        diff = 0.0
        for key in fac:
            na_, nb_ = damping * m_f2a[key] + (1 - damping) * new_a[key], damping * m_f2b[key] + (1 - damping) * new_b[key]; diff = max(diff, np.abs(na_ - m_f2a[key]).max(), np.abs(nb_ - m_f2b[key]).max()); m_f2a[key], m_f2b[key] = na_, nb_
        if diff < 1e-6: break
    belief = np.stack([node_prod(i) for i in range(n)]); pair = {}
    for key in fac:
        a, b = key; va = node_prod(a, (key, 0)); vb = node_prod(b, (key, 1)); j = psi[key] * va[:, None] * vb[None, :]; pair[key] = j / j.sum()
    return belief, pair


def m_step(fac: dict, pair: dict, prior_scale: float = 1.0) -> np.ndarray:
    c11, c10, c00 = (PRIOR_COUNTS[k] * prior_scale for k in ("11", "10", "00")); c11, c10, c00 = c11.copy(), c10.copy(), c00.copy()
    for key, items in fac.items():
        b = pair[key]
        for k, o in items:
            sa = S[k].astype(int); w = {(i, j): sum(b[za, zb] for za in range(NS) for zb in range(NS) if sa[za] == i and sa[zb] == j) for i in (0, 1) for j in (0, 1)}
            for (i, j), mass in w.items():
                if i == 1 and j == 1: c11[0 if o in (0, 1) else o - 1] += mass
                elif i == 0 and j == 0: c00[0 if o in (0, 1) else o - 1] += mass
                elif i == 1 and j == 0: c10[o if o in (0, 1) else o] += mass            # typed image is a: outcome 0 = typed wins
                else: c10[{0: 1, 1: 0, 2: 2, 3: 3}[o]] += mass                           # typed image is b: outcome 1 = typed wins
    return build_table(c11 / c11.sum(), c10 / c10.sum(), c00 / c00.sum())


def posterior_of_images(jud: Judgments, prior_of: np.ndarray, mode: str = "em", em_iters: int = 8, prior_scale: float = 1.0, rng: np.random.Generator | None = None):
    """Posterior over the latent state of every image of the labelled judgments.  Returns (beliefs (n, 5), table, pair beliefs).
    mode 'em' full model, 'prior' = no outcome likelihood (beliefs = prior), 'random' = EM beliefs permuted among the images."""
    table = init_table(prior_scale)
    if mode == "prior":
        pair = {key: np.outer(prior_of[key[0]], prior_of[key[1]]) for key in jud.factors}; return prior_of.copy(), table, pair
    belief = prior_of
    for _ in range(em_iters):
        belief, pair = belief_propagation(prior_of, jud.factors, table); table = m_step(jud.factors, pair, prior_scale)
    belief, pair = belief_propagation(prior_of, jud.factors, table)
    if mode == "random":
        perm = rng.permutation(len(belief)); belief = belief[perm]; pair = {key: np.outer(belief[key[0]], belief[key[1]]) for key in jud.factors}
    return belief, table, pair


def row_probabilities(jud: Judgments, pair: dict, belief: np.ndarray):
    """For every judgment row: P(s_a=0), P(s_b=0) (image a / image b not of the row's type) and P(both not type k), from the pair belief (independent beliefs for rows with a == b)."""
    out = []
    for ia, ib, k, o, key in jud.rows:
        if key is None: pa = belief[ia, k]; out.append((1 - pa, 1 - pa, 1 - pa)); continue
        b = pair[key]; a_first = key[0] == ia
        if not a_first: b = b.T
        p_a1 = b[k].sum(); p_b1 = b[:, k].sum(); p_both0 = b[np.arange(NS) != k][:, np.arange(NS) != k].sum()
        out.append((1 - p_a1, 1 - p_b1, p_both0))
    return np.array(out)


# ------------------------------------------------------------------------------------------ priors from the graph and the soft-source update
def node_prior(gd, paths, cache, q: np.ndarray) -> np.ndarray:
    """q of every path: a graph node reads its own row, a non-node (identity-excluded twin) averages its k nearest nodes."""
    out = np.zeros((len(paths), q.shape[1])); ext = [i for i, p in enumerate(paths) if p not in gd.index]
    for i, p in enumerate(paths):
        if p in gd.index: out[i] = q[gd.index[p]]
    if ext: nb = gd.neighbours_of([paths[i] for i in ext], cache).numpy(); out[ext] = q[nb].mean(1)
    return out


def spread(gd, sources: np.ndarray, alpha: float = G.ALPHA) -> np.ndarray:
    """Label spreading of soft sources (n_nodes, 4) over the graph: normalised (I - alpha S)^-1 Y (rows without mass -> uniform), as ``GraphData.q``."""
    n = len(gd.paths); a = gd.adj.double(); d = a.sum(1).clamp_min(1.0); s = (a / (d[:, None] * d[None, :]).sqrt()).numpy()
    import torch
    f = torch.linalg.solve(torch.eye(n, dtype=torch.float64) - alpha * torch.as_tensor(s), torch.as_tensor(sources, dtype=torch.float64)).clamp_min(0).numpy()
    mass = f.sum(1, keepdims=True); return np.where(mass > 1e-9, f / np.maximum(mass, 1e-9), 1.0 / sources.shape[1])


def source_matrix(gd, extra_nodes: dict[int, np.ndarray] | None = None, hidden: set | None = None, weight: float = 1.0) -> np.ndarray:
    """Typed-anchor one-hots (anchors listed in ``hidden`` removed) plus soft one-hot-like rows of ``extra_nodes`` (posterior over the 4 types, weight ``weight``)."""
    y = np.zeros((len(gd.paths), 4))
    for i, c in gd.source_class.items():
        if hidden and i in hidden: continue
        y[i, COL[c]] = 1.0
    for i, v in (extra_nodes or {}).items():
        if i in gd.source_class and not (hidden and i in hidden): continue
        y[i] += weight * v[:4]
    return y
